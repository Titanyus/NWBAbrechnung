#!/usr/bin/env python3
"""Synthetic creation, structured addresses and in-plant route workflows."""
import json
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect

settings = dict(line.split('=',1) for line in Path('.env').read_text().splitlines() if '=' in line and not line.startswith('#'))
base = 'http://127.0.0.1:3000'
name = 'SYN-Anlage-' + uuid4().hex[:8]
out = Path('docs/ui-plant-routes/screenshots/after')
out.mkdir(parents=True, exist_ok=True)
report = []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':1440,'height':900})
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(base+'/session/new')
    page.get_by_label('E-Mail-Adresse',exact=True).fill('admin@example.test')
    page.get_by_label('Passwort',exact=True).fill(settings['DEMO_PASSWORD'])
    page.get_by_role('button',name='Anmelden',exact=True).click()
    page.locator('#plants-table').wait_for()
    assert page.locator('#plants-table input[type=radio]').count()==0
    page.get_by_role('link',name='Neue Anlage anlegen',exact=True).click()
    page.get_by_label('Anlagenname',exact=True).fill(name)
    page.get_by_label('Straße und Hausnummer',exact=True).fill('Anlagenweg 7')
    page.get_by_label('PLZ',exact=True).fill('01234')
    page.get_by_label('Ort',exact=True).fill('Beispielort')
    page.get_by_label('Technische Hinweise (optional)',exact=True).fill('Synthetische Anlage für die Browserprüfung')
    assert page.locator('#plant_metrics [data-metric=routes]').inner_text()=='0'
    for width,height in [(1280,800),(1440,900),(1920,1080),(2560,1440)]:
        page.set_viewport_size({'width':width,'height':height})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(out/f'new-plant-{width}x{height}.png'))
    page.set_viewport_size({'width':1440,'height':900})
    page.get_by_role('button',name='Anlage speichern',exact=True).click()
    page.locator('#plants-table').wait_for()
    page.get_by_role('link',name=name+': Bearbeiten',exact=True).click()
    page.get_by_role('link',name='Neue Trasse',exact=True).wait_for()
    plant_url=page.url.removesuffix('/edit')
    expect(page.get_by_label('PLZ',exact=True)).to_have_value('01234')
    report.append('Create plant with three separate required address fields; leading postal zero retained')
    # Keep unsaved plant edits while routes have their own transaction/frame.
    page.get_by_label('Technische Hinweise (optional)',exact=True).fill('UNSAVED-PLANT-DRAFT')
    page.evaluate('window.__plantForm=document.querySelector("#plant-form")')
    page.get_by_role('link',name='Neue Trasse',exact=True).click()
    page.get_by_label('Trassenkennung (optional)',exact=True).fill('T-01')
    page.get_by_label('Bezeichnung',exact=True).fill('')
    page.locator('#route_editor form').evaluate('(form)=>{form.noValidate=true}')
    page.get_by_role('button',name='Trasse speichern',exact=True).click()
    page.locator('#route_editor [role=alert]').wait_for()
    expect(page.get_by_label('Trassenkennung (optional)',exact=True)).to_have_value('T-01')
    page.get_by_label('Bezeichnung',exact=True).fill('Nordtrasse')
    page.get_by_role('button',name='Trasse speichern',exact=True).click()
    page.get_by_role('cell',name='Nordtrasse',exact=True).wait_for()
    assert page.evaluate('window.__plantForm===document.querySelector("#plant-form")')
    expect(page.get_by_label('Technische Hinweise (optional)',exact=True)).to_have_value('UNSAVED-PLANT-DRAFT')
    expect(page.locator('[data-metric=routes]')).to_have_text('1')
    page.get_by_role('link',name='Nordtrasse: Trasse bearbeiten',exact=True).click()
    page.get_by_label('Bezeichnung',exact=True).fill('Nordtrasse bearbeitet')
    page.get_by_role('button',name='Trasse speichern',exact=True).click()
    page.get_by_role('cell',name='Nordtrasse bearbeitet',exact=True).wait_for()
    assert page.evaluate('window.__plantForm===document.querySelector("#plant-form")')
    expect(page.get_by_label('Technische Hinweise (optional)',exact=True)).to_have_value('UNSAVED-PLANT-DRAFT')
    page.get_by_role('button',name='Anlage speichern',exact=True).click()
    page.locator('#plants-table').wait_for()
    report.append('Route validation/create/edit update only routes/metrics; unsaved plant draft survives')
    # Use real UI forms for customer and house, each reusing the address partial.
    page.goto(plant_url+'/customers/new')
    page.get_by_label('Firmenname (bei Unternehmen)',exact=True).fill(name+' Kunde')
    page.get_by_label('Straße und Hausnummer',exact=True).fill('Kundenweg 2')
    page.get_by_label('PLZ',exact=True).fill('00123')
    page.get_by_label('Ort',exact=True).fill('Kundenort')
    page.get_by_role('button',name='Kunde speichern',exact=True).click()
    page.get_by_role('heading',name=name+' Kunde',exact=True).wait_for()
    assert '00123 Kundenort' in page.locator('main').inner_text()
    page.goto(plant_url+'/connections/new')
    page.get_by_label('Anschlussnummer',exact=True).fill('H-01')
    page.get_by_label('Straße und Hausnummer',exact=True).fill('Hausweg 3')
    page.get_by_label('PLZ',exact=True).fill('00456')
    page.get_by_label('Ort',exact=True).fill('Hausort')
    page.get_by_label('Trasse',exact=True).select_option(label='Nordtrasse bearbeitet')
    page.get_by_role('button',name='Anschluss speichern',exact=True).click()
    page.get_by_role('heading',name='Anschluss H-01',exact=True).wait_for()
    assert '00456 Hausort' in page.locator('main').inner_text()
    report.append('Customer and house creation use the same structured address fields and preserve postal strings')
    for status in ['active','draft','cancelled','ended']:
        page.goto(plant_url+'/supply_contracts/new')
        customer_option=page.locator('#draft_customer_id option').filter(has_text=name+' Kunde')
        page.get_by_label('Kunde / Rechnungsempfänger',exact=True).select_option(customer_option.get_attribute('value'))
        connection_option=page.locator('#draft_connection_id option').filter(has_text='H-01')
        page.get_by_label('Verbrauchsstelle / Anschluss',exact=True).select_option(connection_option.get_attribute('value'))
        page.get_by_label('Vertragsnummer',exact=True).fill('V-'+status)
        page.get_by_label('Vertragsbeginn',exact=True).fill('2025-01-01' if status=='ended' else '2026-01-01')
        if status=='ended':page.get_by_label('Vertragsende (optional)',exact=True).fill('2025-12-31')
        page.get_by_label('Vertragsstatus',exact=True).select_option(status)
        page.get_by_role('button',name='Vertrag speichern',exact=True).click()
        page.get_by_role('heading',name='Vertragsakte V-'+status,exact=True).wait_for()
    page.goto(plant_url+'/edit')
    expect(page.locator('[data-metric=contracts]')).to_have_text('4')
    expect(page.locator('[data-metric=connections]')).to_have_text('1')
    numbers=page.locator('#plant-routes-table tbody tr td.number').all_text_contents()
    assert numbers==['1','4'],numbers
    for width,height in [(1280,800),(1440,900),(1920,1080),(2560,1440)]:
        page.set_viewport_size({'width':width,'height':height})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        assert page.locator('.contract-topbar').evaluate('(el)=>getComputedStyle(el).backgroundColor')=='rgb(43, 66, 31)'
        page.screenshot(path=str(out/f'edit-plant-{width}x{height}.png'))
    report.append('Automatic metrics count 1 house and all 4 contracts across active/draft/cancelled/ended without multiplying house count')
    page.goto(base+'/plants')
    page.get_by_label('Anlage oder Adresse suchen',exact=True).fill(name)
    expect(page.locator('#plants-table tbody tr')).to_have_count(1)
    page.get_by_role('link',name=name+': Bearbeiten',exact=True).click()
    page.locator('#plant-form').wait_for()
    page.get_by_role('link',name='Abbrechen',exact=True).click()
    page.wait_for_load_state('networkidle')
    page.get_by_label('Anlage oder Adresse suchen',exact=True).fill(name)
    expect(page.locator('#plants-table tbody tr')).to_have_count(1)
    page.get_by_role('button',name=name+': Anlage auswählen',exact=True).click()
    page.locator('#contract_browser').wait_for()
    assert page.get_by_label('Anlage',exact=True).input_value()==plant_url.rsplit('/',1)[1]
    # Header switch remains the same authorized function.
    page.get_by_label('Anlage',exact=True).select_option(label='Testanlage 01')
    page.get_by_role('button',name='Wechseln',exact=True).click()
    page.locator('#contract_browser').wait_for()
    expect(page.get_by_label('Anlage',exact=True)).not_to_have_value(plant_url.rsplit('/',1)[1])
    report.append('Direct row edit, row plant selection and header switch remain distinct working actions')
    assert not errors,errors
    report.append('No JavaScript errors; existing green/gold theme unchanged')
    browser.close()
Path('docs/ui-plant-routes/workspace-checks.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
