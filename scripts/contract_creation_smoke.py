#!/usr/bin/env python3
"""Master/detail creation with bounded live lookups and atomic retry on synthetic data."""
import argparse
import json
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect
parser = argparse.ArgumentParser()
parser.add_argument('--env-file', default='.env')
parser.add_argument('--base', default='http://127.0.0.1:3000')
parser.add_argument('--fixtures', default='/tmp/nwb-ui-fixture.json')
parser.add_argument('--output', default='docs/ui-contract-create')
args = parser.parse_args()
settings = dict((line.split('=', 1) for line in Path(args.env_file).read_text().splitlines() if '=' in line and (not line.startswith('#'))))
paths = json.loads(Path(args.fixtures).read_text())
base = args.base.rstrip('/')
prefix = 'INLINE-' + uuid4().hex[:8]
out = Path(args.output, 'screenshots')
out.mkdir(parents=True, exist_ok=True)
checks = []
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    page = b.new_page(viewport={'width': 1440, 'height': 900})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(base + '/session/new')
    page.get_by_label('E-Mail-Adresse', exact=True).fill('admin@example.test')
    page.get_by_label('Passwort', exact=True).fill(settings['DEMO_PASSWORD'])
    page.get_by_role('button', name='Anmelden', exact=True).click()
    page.locator('#plants-table').wait_for()
    page.goto(base + paths['contracts'])
    page.locator('.contract-item').first.wait_for()
    page.wait_for_function('() => window.Stimulus?.getControllerForElementAndIdentifier(document.body, "live-search")')
    page.get_by_label('Suche', exact=True).fill('Beispiel')
    page.wait_for_function('() => JSON.parse(document.querySelector("[data-contract-browser-query-value]").dataset.contractBrowserQueryValue).q === "Beispiel"')
    baseline_count = int(page.locator('#contract_count').inner_text().split()[0])
    assert baseline_count >= 150
    selected_link = page.locator('.contract-item a').nth(12)
    selected_link.scroll_into_view_if_needed()
    selected = selected_link.get_attribute('data-contract-id')
    selected_link.click()
    expect(page.locator('#contract_workspace')).to_have_attribute('data-contract-id', selected)
    page.evaluate('window.__list=document.querySelector(".contract-list-scroll")')
    scroll = page.locator('.contract-list-scroll').evaluate('(el)=>el.scrollTop')
    page.get_by_role('link', name='Vertrag anlegen', exact=True).click()
    page.locator('#contract_draft_workspace').wait_for()
    assert page.evaluate('window.__list===document.querySelector(".contract-list-scroll")')
    assert abs(page.locator('.contract-list-scroll').evaluate('(el)=>el.scrollTop') - scroll) < 2
    assert page.locator('#draft_customer_id option').count() <= 21
    assert page.locator('#draft_connection_id option').count() <= 21
    page.get_by_role('link', name='Abbrechen', exact=True).first.click()
    expect(page.locator('#contract_workspace')).to_have_attribute('data-contract-id', selected)
    expect(page.get_by_label('Suche', exact=True)).to_have_value('Beispiel')
    checks.append('New/cancel change only right frame and preserve list DOM, scroll, filter and selected contract')
    page.get_by_role('link', name='Vertrag anlegen', exact=True).click()
    page.locator('#contract_draft_workspace').wait_for()
    page.get_by_label('Kunde suchen', exact=True).fill('UX-150')
    customer_option = page.locator('#draft_customer_id option').filter(has_text='UX-150')
    expect(customer_option).to_have_count(1)
    page.get_by_label('Kunde / Rechnungsempfänger', exact=True).select_option(customer_option.get_attribute('value'))
    page.get_by_label('Anschluss suchen', exact=True).fill('UX-150')
    connection_option = page.locator('#draft_connection_id option').filter(has_text='UX-150')
    expect(connection_option).to_have_count(1)
    page.get_by_label('Verbrauchsstelle / Anschluss', exact=True).select_option(connection_option.get_attribute('value'))
    expect(page.locator('#draft_meter')).to_contain_text('UX-150')
    assert page.locator('#draft_new_meter').count() == 0
    for width, height in [(1280, 800), (1440, 900), (1920, 1080), (2560, 1440)]:
        page.set_viewport_size({'width': width, 'height': height})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.locator('.contract-detail-scroll').evaluate('(el)=>el.scrollTop=0')
        page.screenshot(path=str(out / f'existing-{width}x{height}.png'))
    page.set_viewport_size({'width': 1440, 'height': 900})
    page.get_by_label('Vertragsnummer', exact=True).fill(prefix + '-existing')
    page.get_by_label('Vertragsbeginn', exact=True).fill('2027-01-01')
    page.get_by_role('button', name='Vertrag speichern', exact=True).click()
    page.get_by_role('heading', name='Vertragsakte ' + prefix + '-existing', exact=True).wait_for()
    expect(page.locator('#contract_count')).to_have_text(f'{baseline_count + 1} Verträge')
    assert page.evaluate('window.__list===document.querySelector(".contract-list-scroll")')
    assert '/new' not in page.url
    page.get_by_role('link', name='Kundendaten bearbeiten', exact=True).click()
    page.get_by_label('Telefon', exact=True).fill('0000-INLINE')
    page.get_by_role('button', name='Kunde speichern', exact=True).click()
    expect(page.locator('#contract_customer')).to_contain_text('0000-INLINE')
    checks.append('Bounded full-dataset lookups find UX-150; active meter stays attached; existing record creates and inline edit still works')
    page.get_by_role('link', name='Vertrag anlegen', exact=True).click()
    page.locator('#contract_draft_workspace').wait_for()
    page.get_by_label('Neuen Kunden anlegen', exact=True).check()
    page.get_by_label('Neuen Anschluss anlegen', exact=True).check()
    page.locator('#draft_new_meter').wait_for()
    page.get_by_label('Firmenname (bei Unternehmen)', exact=True).fill(prefix + ' Kunde')
    customer = page.locator('fieldset[data-draft-group=customer][data-draft-choice=new]')
    customer.get_by_label('Straße und Hausnummer', exact=True).fill('Kundenweg 1')
    customer.get_by_label('PLZ', exact=True).fill('00123')
    customer.get_by_label('Ort', exact=True).fill('Kundenort')
    house = page.locator('fieldset[data-draft-group=connection][data-draft-choice=new]')
    house.get_by_label('Anschlussnummer', exact=True).fill(prefix + '-house')
    house.get_by_label('Straße und Hausnummer', exact=True).fill('Hausweg 2')
    house.get_by_label('PLZ', exact=True).fill('00456')
    house.get_by_label('Ort', exact=True).fill('Hausort')
    house.get_by_label('Trasse', exact=True).select_option(index=1)
    page.get_by_label('Zähler anlegen', exact=True).check()
    page.get_by_label('Zählernummer', exact=True).fill(prefix + '-meter')
    page.get_by_label('Einbaudatum', exact=True).fill('2026-01-01')
    page.get_by_label('Anfangszählerstand', exact=True).fill('-1')
    page.get_by_label('Vertragsnummer', exact=True).fill(prefix + '-new')
    page.get_by_label('Vertragsbeginn', exact=True).fill('2026-01-01')
    page.get_by_label('Vertragsstatus', exact=True).select_option('active')
    page.locator('#contract-draft-form').evaluate('(form)=>form.noValidate=true')
    page.get_by_role('button', name='Vertrag speichern', exact=True).click()
    page.locator('#contract_draft_workspace [role=alert]').wait_for()
    expect(page.get_by_label('Firmenname (bei Unternehmen)', exact=True)).to_have_value(prefix + ' Kunde')
    expect(page.get_by_label('Zählernummer', exact=True)).to_have_value(prefix + '-meter')
    expect(page.get_by_label('Neuen Kunden anlegen', exact=True)).to_be_checked()
    expect(page.get_by_label('Neuen Anschluss anlegen', exact=True)).to_be_checked()
    page.screenshot(path=str(out / 'validation-1440x900.png'))
    page.get_by_label('Anfangszählerstand', exact=True).fill('0.123456')
    page.get_by_role('button', name='Vertrag speichern', exact=True).click()
    page.get_by_role('heading', name='Vertragsakte ' + prefix + '-new', exact=True).wait_for()
    expect(page.locator('#contract_customer')).to_contain_text('00123 Kundenort')
    expect(page.locator('#contract_connection')).to_contain_text('00456 Hausort')
    expect(page.locator('#contract_meter')).to_contain_text(prefix + '-meter')
    expect(page.locator('#contract_meter')).to_contain_text('0,123456')
    expect(page.get_by_label('Suche', exact=True)).to_have_value('Beispiel')
    assert page.evaluate('window.__list===document.querySelector(".contract-list-scroll")')
    page.screenshot(path=str(out / 'created-1440x900.png'))
    checks.append('New customer/house/meter created inline; failed reading keeps modes/values and successful retry creates one coherent contract with exact initial value')
    colors = page.evaluate("()=>{const s=getComputedStyle(document.documentElement);return {page:s.getPropertyValue('--page').trim(),surface:s.getPropertyValue('--surface').trim()}}")
    assert colors['page'] != colors['surface']
    checks.append('Page background derives a darker tone from existing tokens; white panels and theme palette remain')
    page.get_by_label('Suche', exact=True).fill('UX-150')
    page.wait_for_function('() => JSON.parse(document.querySelector("[data-contract-browser-query-value]").dataset.contractBrowserQueryValue).q === "UX-150"')
    page.evaluate('window.__insertList=document.querySelector(".contract-list-scroll")')
    page.get_by_role('link', name='Vertrag anlegen', exact=True).click()
    page.locator('#contract_draft_workspace').wait_for()
    page.get_by_label('Kunde suchen', exact=True).fill('UX-150')
    option = page.locator('#draft_customer_id option').filter(has_text='UX-150')
    expect(option).to_have_count(1)
    page.get_by_label('Kunde / Rechnungsempfänger', exact=True).select_option(option.get_attribute('value'))
    page.get_by_label('Anschluss suchen', exact=True).fill('UX-150')
    option = page.locator('#draft_connection_id option').filter(has_text='UX-150')
    expect(option).to_have_count(1)
    page.get_by_label('Verbrauchsstelle / Anschluss', exact=True).select_option(option.get_attribute('value'))
    page.get_by_label('Vertragsnummer', exact=True).fill(prefix + '-insert')
    page.get_by_label('Vertragsbeginn', exact=True).fill('2027-01-01')
    page.get_by_role('button', name='Vertrag speichern', exact=True).click()
    page.get_by_role('heading', name='Vertragsakte ' + prefix + '-insert', exact=True).wait_for()
    new_id = page.locator('#contract_workspace').get_attribute('data-contract-id')
    expect(page.locator('.contract-item a[data-contract-id="' + new_id + '"]')).to_have_count(1)
    expect(page.locator('.contract-item a[data-contract-id="' + new_id + '"]')).to_have_attribute('aria-current', 'page')
    assert page.evaluate('window.__insertList===document.querySelector(".contract-list-scroll")')
    checks.append('Matching newly created row is inserted once and selected without replacing the list')
    assert not errors, errors
    checks.append('No JavaScript errors')
    b.close()
Path(args.output, 'browser-checks.json').write_text(json.dumps(checks, indent=2) + '\n')
print(json.dumps(checks, indent=2))
